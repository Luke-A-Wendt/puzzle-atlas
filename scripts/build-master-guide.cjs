'use strict';
// Generate small setup tables for original, physically checked Master Pyraminx
// guide operations. This enumerates only ordered triples/pairs of piece slots,
// never complete puzzle configurations. Run: node scripts/build-master-guide.cjs
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const E=require('../dist/games/masterpyraminx-engine.js'),model=E.create();
const specs={
  midge:{kind:'midge',mode:'cycle',core:"Lw' Uw Lw Uw Lw' Uw Lw",base:['UB midge','UL midge','UR midge']},
  flip:{kind:'midge',mode:'pair',core:"Uw Lw Uw' Rw Uw' Rw' Uw Lw'",base:['UL midge','UR midge']},
  center:{kind:'center',mode:'cycle',core:"Rw Uw Rw' Uw Rw Uw Rw' Uw U'",base:['U center','B center','L center']},
  wing:{kind:'wing',mode:'cycle',core:"U Lw U' Lw'",base:['BL wing','UR wing','UL wing']}
};
const moves=model.configs.filter(c=>!c.tip).flatMap(c=>[c.id,c.id+"'"]);
const canon=(a,mode)=>mode==='pair'?a.slice().sort().join('|'):[a.join('|'),[a[1],a[2],a[0]].join('|'),[a[2],a[0],a[1]].join('|')].sort()[0];
const permutations=Object.fromEntries(moves.map(t=>{model.reset().applyMove(t);return[t,Object.fromEntries(model.pieces.map(p=>[p.name,model.pieces[p.slot].name]))];}));
const data={};
for(const [name,spec]of Object.entries(specs)){
  const slots=model.pieces.filter(p=>p.kind===spec.kind).map(p=>p.name).sort(),paths={[canon(spec.base,spec.mode)]:''},queue=[spec.base];
  for(let i=0;i<queue.length;i++){
    const old=queue[i],word=paths[canon(old,spec.mode)];
    for(const move of moves){const next=old.map(slot=>permutations[move][slot]),key=canon(next,spec.mode);if(paths[key]!==undefined)continue;paths[key]=word?word+' '+move:move;queue.push(next);}
  }
  // In A4 the two directions of a 3-cycle form different conjugacy classes.
  // Four center setups cover one class; invert the core for the other four.
  const n=slots.length,expected=spec.mode==='pair'?n*(n-1)/2:n*(n-1)*(n-2)/(name==='center'?6:3);
  assert.equal(Object.keys(paths).length,expected,name+' tuple orbit must be complete');
  data[name]={...spec,slots,paths};
}
const output='/* Generated by scripts/build-master-guide.cjs; verified against MasterPyraminxEngine. */\n(function(root){\n\'use strict\';\nconst data='+JSON.stringify(data)+';\nroot.MASTER_GUIDE_DATA=data;if(typeof module!==\'undefined\'&&module.exports)module.exports=data;\n})(typeof window!==\'undefined\'?window:globalThis);\n';
const target=path.resolve(__dirname,'../dist/master-guide-data.js');fs.writeFileSync(target,output);
console.log(JSON.stringify({bytes:Buffer.byteLength(output),setups:Object.fromEntries(Object.entries(data).map(([k,v])=>[k,Object.keys(v.paths).length]))}));
