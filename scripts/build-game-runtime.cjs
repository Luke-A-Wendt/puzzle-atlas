#!/usr/bin/env node
'use strict';
// Keep the editable components, but send two shared ordered files to the browser.
// No minifier, package installation or runtime loader is required.
const fs=require('node:fs'),path=require('node:path');
const groups=Object.freeze({
 'game-controls.bundle.js':['ring-map-navigation.js','play-controls.js','puzzle-axis-display.js','move-journal.js','puzzle-selection-3d.js'],
 'game-solver.bundle.js':['play-timer.js','ring-panel.js','constrained-solver-core.js','constrained-solver.js']
});
const escape=value=>value.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
function contents(files,dir){return '/* Generated by scripts/build-game-runtime.cjs; edit the named component files. */\n'+files.map(file=>'\n;/* Component: '+file+' */\n'+fs.readFileSync(path.join(dir,file),'utf8')+'\n').join('');}
function packHTML(html){
 for(const [bundle,files]of Object.entries(groups)){
  const packed=new RegExp('<script\\b[^>]*\\bsrc="'+escape(bundle)+'(?:\\?[^"#]*)?"[^>]*><\\/script>','g');
  const unpacked=new RegExp(files.map(file=>'<script src="'+escape(file)+'(?:\\?[^"#]*)?"><\\/script>').join('\\s*'),'g');
  const matches=[...html.matchAll(packed),...html.matchAll(unpacked)];
  if(matches.length!==1)throw Error('Expected one ordered '+bundle+' group; found '+matches.length);
  const old=matches[0][0],query=/src="[^"?]+(\?[^"#]*)"/.exec(old)?.[1]||'';
  html=html.replace(old,'<script src="'+bundle+query+'" data-sources="'+files.join(' ')+'"></script>');
 }
 return html;
}
function build(root=path.resolve(__dirname,'../dist')){
 const dir=path.join(root,'games'),pages=fs.readdirSync(dir).filter(name=>name.endsWith('.html'));
 const output=pages.map(name=>[path.join(dir,name),packHTML(fs.readFileSync(path.join(dir,name),'utf8'))]);
 for(const [bundle,files]of Object.entries(groups))fs.writeFileSync(path.join(dir,bundle),contents(files,dir));
 for(const [file,html]of output)fs.writeFileSync(file,html);
 return {pages:pages.length,bundles:Object.keys(groups).length,removedRequestsPerPuzzle:7};
}
module.exports={groups,contents,packHTML,build};
if(require.main===module)console.log(JSON.stringify(build()));
